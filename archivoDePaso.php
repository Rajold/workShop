Una estructura sencilla podría ser:

CCC-TTT-EEE-MMM

Donde:

CCC = Categoría (3 letras)
TTT = Tipo o función (3 letras)
EEE = Especificación (2-4 caracteres)
MMM = Número consecutivo o variante
Ejemplos de categorías
